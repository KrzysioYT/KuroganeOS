#!/usr/bin/env python3
"""Generate the compact freestanding DejaVu Sans UI glyph atlas."""

from __future__ import annotations

import argparse
import base64
from pathlib import Path

from PIL import ImageFont


FONT_SIZES = (8, 10, 12, 16, 20, 24, 32)
CODEPOINTS = tuple(sorted(set(
    tuple(range(0x20, 0x7F))
    + tuple(range(0xA0, 0x100))
    + (
        0x0104, 0x0105, 0x0106, 0x0107, 0x0118, 0x0119,
        0x0141, 0x0142, 0x0143, 0x0144, 0x00D3, 0x00F3,
        0x015A, 0x015B, 0x0179, 0x017A, 0x017B, 0x017C,
        0xFFFD,
    )
)))


def format_array(values: list[str], indent: str = "    ") -> str:
    return "\n".join(
        indent + ", ".join(values[offset : offset + 8]) + ","
        for offset in range(0, len(values), 8)
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--normal", required=True, type=Path)
    parser.add_argument("--bold", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    arguments = parser.parse_args()

    fonts = (arguments.normal, arguments.bold)
    coverage: list[int] = []
    metrics: list[str] = []
    ascents: list[str] = []
    line_heights: list[str] = []
    kerning_offsets = [0]
    kerning_pairs: list[str] = []

    for font_path in fonts:
        for size in FONT_SIZES:
            font = ImageFont.truetype(str(font_path), size=size)
            ascent, descent = font.getmetrics()
            ascents.append(str(ascent))
            line_heights.append(str(ascent + descent))

            advances_26_6: list[int] = []
            for codepoint in CODEPOINTS:
                character = chr(codepoint)
                mask, (bearing_x, bearing_y) = font.getmask2(
                    character, mode="L", anchor="ls"
                )
                width, height = mask.size
                advance_26_6 = int(round(font.getlength(character) * 64))
                if width > 255 or height > 255 or advance_26_6 > 65535:
                    raise ValueError(f"glyph U+{codepoint:04X} exceeds atlas limits")
                advances_26_6.append(advance_26_6)

                pixel_offset = len(coverage)
                pixels = list(mask)
                coverage.extend((pixel * 15 + 127) // 255 for pixel in pixels)
                if len(coverage) & 1:
                    coverage.append(0)
                metrics.append(
                    "    {%d, %d, %d, %d, %d, %d},"
                    % (
                        width, height, bearing_x, bearing_y,
                        advance_26_6, pixel_offset,
                    )
                )

            for left_index, left in enumerate(CODEPOINTS):
                for right_index, right in enumerate(CODEPOINTS):
                    pair_advance = int(round(font.getlength(chr(left) + chr(right)) * 64))
                    adjustment = (
                        pair_advance
                        - advances_26_6[left_index]
                        - advances_26_6[right_index]
                    )
                    if adjustment:
                        if adjustment < -32768 or adjustment > 32767:
                            raise ValueError("kerning adjustment exceeds atlas limits")
                        pair_key = left_index * len(CODEPOINTS) + right_index
                        kerning_pairs.append(
                            "    {%dU, %d}," % (pair_key, adjustment)
                        )
            kerning_offsets.append(len(kerning_pairs))

    packed = bytes(
        (coverage[offset] << 4) | coverage[offset + 1]
        for offset in range(0, len(coverage), 2)
    )
    encoded = base64.b64encode(packed).decode("ascii")
    codepoint_values = ["0x%04x" % codepoint for codepoint in CODEPOINTS]
    size_values = [str(size) for size in FONT_SIZES]

    source = f"""// Generated by scripts/generate-font-atlas.py; do not edit.
#pragma once

#include <stddef.h>
#include <stdint.h>

namespace graphics::font_atlas {{
constexpr size_t kGlyphCount = {len(CODEPOINTS)}U;
constexpr size_t kSizeCount = {len(FONT_SIZES)}U;
constexpr uint32_t kSizes[kSizeCount] = {{
{format_array(size_values)}
}};
constexpr uint32_t kCodepoints[kGlyphCount] = {{
{format_array(codepoint_values)}
}};
struct Metrics {{
    uint16_t width;
    uint16_t height;
    int16_t bearing_x;
    int16_t bearing_y;
    uint16_t advance_26_6;
    uint32_t pixel_offset;
}};
constexpr uint8_t kAscents[2U * kSizeCount] = {{
{format_array(ascents)}
}};
constexpr uint8_t kLineHeights[2U * kSizeCount] = {{
{format_array(line_heights)}
}};
constexpr Metrics kMetrics[2U * kSizeCount * kGlyphCount] = {{
{chr(10).join(metrics)}
}};
struct KerningPair{{
    uint32_t key;
    int16_t adjustment_26_6;
}};
constexpr size_t kKerningStyleCount = 2U * kSizeCount;
constexpr size_t kKerningPairCount = {len(kerning_pairs)}U;
constexpr uint32_t kKerningOffsets[kKerningStyleCount + 1U] = {{
{format_array([str(offset) + "U" for offset in kerning_offsets])}
}};
constexpr KerningPair kKerningPairs[kKerningPairCount] = {{
{chr(10).join(kerning_pairs)}
}};
constexpr size_t kCoverage4DecodedSize = {len(packed)}U;
constexpr char kCoverage4Base64[] =
{chr(10).join('    "' + encoded[offset : offset + 96] + '"' for offset in range(0, len(encoded), 96))};
}} // namespace graphics::font_atlas
"""
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text(source, encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
